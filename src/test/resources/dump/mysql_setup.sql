-- # create databases
CREATE DATABASE IF NOT EXISTS MYSQL_SCHEMA;

CREATE TABLE IF NOT EXISTS MYSQL_SCHEMA.USERS
(
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    DEPOSIT DOUBLE DEFAULT NULL,
    USERNAME VARCHAR(20) UNIQUE NOT NULL,
    PASSWORD VARCHAR(64) NOT NULL,
    EMAIL VARCHAR(64) NOT NULL,
    STATE TINYINT(1) NOT NULL,
    DESCRIPTION VARCHAR(20),
    ROLES VARCHAR(200) NOT NULL,
    DATA JSON NOT NULL,
    IS_ACTIVE BOOLEAN,
    CREATE_DATE DATETIME NOT NULL,
    UPDATE_DATE DATETIME DEFAULT NULL
);

CREATE TABLE IF NOT EXISTS MYSQL_SCHEMA.USERS2
(
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    USERNAME VARCHAR(20) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS MYSQL_SCHEMA.TEST (
  test VARCHAR(255)
);

CREATE TABLE MYSQL_SCHEMA.TEMP (
	ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(20) UNIQUE NOT NULL,
	AMOUNT DECIMAL(18,9) NULL,
	IS_ACTIVE BOOLEAN
);
