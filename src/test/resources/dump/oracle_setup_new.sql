DECLARE
    v_container VARCHAR2(128);
    v_pdb       VARCHAR2(128);
BEGIN
    v_container := SYS_CONTEXT('USERENV', 'CON_NAME');

    IF v_container = 'CDB$ROOT' THEN
        SELECT name
          INTO v_pdb
          FROM v$pdbs
         WHERE name <> 'PDB$SEED'
           AND open_mode = 'READ WRITE'
         FETCH FIRST 1 ROW ONLY;

        EXECUTE IMMEDIATE
            'ALTER SESSION SET CONTAINER = "' || v_pdb || '"';
    END IF;
END;
/


DECLARE
    v_pdb       VARCHAR2(128);
    v_service   NUMBER;
BEGIN
    v_pdb := SYS_CONTEXT('USERENV', 'CON_NAME');

    -- XE 21 already has XEPDB1 service.
    -- Free 23 normally has FREEPDB1, so create XEPDB1 alias.
    IF v_pdb <> 'XEPDB1' THEN

        SELECT COUNT(*)
          INTO v_service
          FROM v$services
         WHERE UPPER(name) = 'XEPDB1';

        IF v_service = 0 THEN
            DBMS_SERVICE.CREATE_SERVICE(
                service_name => 'XEPDB1',
                network_name => 'XEPDB1'
            );
        END IF;

        DBMS_SERVICE.START_SERVICE('XEPDB1');
    END IF;
END;
